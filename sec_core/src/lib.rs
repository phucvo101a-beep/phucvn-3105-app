/// Verify license key from C / Swift
#[no_mangle]
pub extern "C" fn sec_core_verify_key(key_ptr: *const c_char) -> bool {
    if key_ptr.is_null() {
        return false;
    }
    if let Ok(key_str) = unsafe { CStr::from_ptr(key_ptr) }.to_str() {
        verify_license_with_server(key_str).is_ok()
    } else {
        false
    }
}

/// Check if currently in valid activated state (using opaque predicate)
#[no_mangle]
pub extern "C" fn sec_core_is_activated() -> bool {
    sabotage::is_state_valid() && sabotage::get_active_session_token().is_some()
}

/// Retrieve server-decrypted session payload (offsets / decryption keys)
#[no_mangle]
pub extern "C" fn sec_core_get_session_payload(out_buf: *mut u8, max_len: usize) -> usize {
    if let Some(token) = sabotage::get_active_session_token() {
        let copy_len = token.len().min(max_len);
        unsafe {
            core::ptr::copy_nonoverlapping(token.as_ptr(), out_buf, copy_len);
        }
        copy_len
    } else {
        0
    }
}

