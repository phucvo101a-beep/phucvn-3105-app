/// Mach-O Constructor: Executes immediately upon `dlopen` / `LC_LOAD_DYLIB` before `main()`
#[used]
#[no_mangle]
#[link_section = "__DATA,__mod_init_func"]
pub static INITIALIZER: extern "C" fn() = sec_core_constructor;

extern "C" fn sec_core_constructor() {
    // 1. Intelligent Anti-Debug:
    // In iOS 18.7.2 - 18.7.10 (LocalDev window), skip PT_DENY_ATTACH at startup so LocalDev tunnel can attach.
    // For iOS 15..17, 18.0..18.7.1, 26, 27.2.1: strictly call PT_DENY_ATTACH immediately.
    if !anti_debug::is_localdev_supported_ios() {
        anti_debug::deny_debugger();
    }

    // 2. Initial Anti-Debug & Anti-Hook Checks
    if anti_debug::check_debugger_presence() {
        sabotage::trigger_tamper_flag();
    }

    if anti_hook::check_hook_environment() {
        sabotage::trigger_tamper_flag();
    }

    // 3. Launch continuous background watchdog
    std::thread::spawn(move || {
        let mut loop_count: u64 = 0;
        loop {
            std::thread::sleep(Duration::from_secs(5));

            // Anti-Debug check (intelligent LocalDev-aware)
            if anti_debug::check_debugger_presence() {
                sabotage::trigger_tamper_flag();
                break;
            }

            // Anti-Hook check (always scans blacklist dylds, ports 27042/27043, trampoline hooks)
            if anti_hook::check_hook_environment() {
                sabotage::trigger_tamper_flag();
                break;
            }

            // Periodic Self-Integrity Check every ~15 seconds strictly on libsec_core itself
            // Main app binary hash is verified server-side to allow static patch compatibility
            loop_count += 1;
            if loop_count % 3 == 0 {
                if let Some(_hash) = integrity::compute_sec_core_hash() {
                    // Security dylib self-integrity verified
                }
            }
        }
    });
}

/// Core function to perform complete Zero-Trust validation against `api_v2.php`
pub fn verify_license_with_server(license_key: &str) -> Result<sabotage::SessionPayload, String> {
    if !sabotage::is_state_valid() {
        sabotage::trigger_tamper_flag();
        return Err(obfstr!("Security state invalid").to_string());
    }

    // 1. Collect Hardware Fingerprint & Integrity Hash
    let device_fp = device::generate_device_fingerprint();
    let app_hash = integrity::compute_main_app_hash()
        .map(|h| crypto::hex_encode(&h))
        .unwrap_or_else(|| "00000000000000000000000000000000".to_string());

    let client_ts = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();

    // Generate 16-byte random challenge
    let mut challenge_bytes = [0u8; 16];
    rand::RngCore::fill_bytes(&mut rand::rngs::OsRng, &mut challenge_bytes);
    let challenge = crypto::hex_encode(&challenge_bytes);

    let client_payload = crypto::ClientRequestPayload {
        license_key: license_key.to_string(),
        device_fp: device_fp.clone(),
        client_ts,
        challenge: challenge.clone(),
        app_hash,
    };

    // 2. Encrypt with X25519 + XChaCha20-Poly1305
    let (wire_packet, session) = crypto::CryptoSession::prepare_request(
        &client_payload,
        &SERVER_X25519_PUB,
        PRE_SHARED_PEPPER,
    )?;

    let wire_json = serde_json::to_string(&wire_packet)
        .map_err(|e| format!("JSON serialize error: {:?}", e))?;

    // 3. Send over pinned TLS directly to `https://20-10.store/api_v2.php`
    let domain = obfstr!("20-10.store");
    let path = obfstr!("/api_v2.php");

    let response_body = network::post_encrypted_json(
        domain,
        path,
        &wire_json,
        PRIMARY_SPKI_PIN,
        BACKUP_SPKI_PIN,
    )?;

    // 4. Parse server encrypted response
    let server_packet: crypto::ServerEncryptedPacket = serde_json::from_str(&response_body)
        .map_err(|e| format!("Server JSON error: {:?} Body: {}", e, response_body))?;

    // 5. Decrypt and verify Ed25519 signature
    let server_response = session.verify_and_decrypt_response(
        &server_packet,
        &SERVER_ED25519_PUB,
    )?;

    // 6. Validate status and timestamps
    if server_response.status != obfstr!("active") {
        return Err(format!("License inactive or expired (status: {})", server_response.status));
    }

    if server_response.device_fp != device_fp {
        return Err(obfstr!("Device fingerprint mismatch").to_string());
    }

    if server_response.exp_ts != 0 && server_response.exp_ts < server_response.server_ts {
        return Err(obfstr!("License has expired").to_string());
    }

    let payload = sabotage::SessionPayload {
        token: crypto::hex_decode(&server_response.session_payload).unwrap_or_default(),
        exp_timestamp: server_response.exp_ts,
        server_timestamp: server_response.server_ts,
    };

    sabotage::set_active_session(payload);

    // 7. Start periodic background heartbeat every 5 minutes
    let key_clone = license_key.to_string();
    std::thread::spawn(move || {
        loop {
            std::thread::sleep(Duration::from_secs(300));
            if verify_license_with_server(&key_clone).is_err() {
                sabotage::trigger_tamper_flag();
                break;
            }
        }
    });

    Ok(sabotage::SessionPayload::default())
}

