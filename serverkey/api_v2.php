<?php
/**
 * PHUCVN STUDIO - Zero-Trust Cryptographic Activation Endpoint (API v2)
 * End-to-End Encryption: X25519 ECDH + HKDF-SHA256 + XChaCha20-Poly1305 + Ed25519
 *
 * Placed at: https://20-10.store/api_v2.php
 */

declare(strict_types=1);

if (session_status() === PHP_SESSION_NONE) {
    @session_start();
}

require_once __DIR__ . '/config.php';

header('Content-Type: application/json; charset=UTF-8');
header('X-Content-Type-Options: nosniff');
header('X-Frame-Options: DENY');

// Ensure ext-sodium is available
if (!extension_loaded('sodium')) {
    http_response_code(500);
    echo json_encode(['error' => 'ext-sodium is required for API v2 security']);
    exit;
}

// ====================================================================
// SERVER MASTER CRYPTOGRAPHIC KEYS
// Replace these with keys generated by `tools/keygen`
// ====================================================================

// Server X25519 Private Key (Hex, 32 bytes)
define('SERVER_X25519_PRIV_HEX', 'a1b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d7e8f90');
// Server Ed25519 Private Key (Hex, 64 bytes - seed + pub)
define('SERVER_ED25519_PRIV_HEX', '50485543564e33313035205345435552495459204b4559205041495220454432a1b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d7e8f90');
// Pre-Shared Pepper (Same string as embedded in Rust)
define('PRE_SHARED_PEPPER', '3105-PHUCVN-SUPER-PEPPER-SALT-2026-XNU');
define('PROTOCOL_INFO', '3105-X-PHUCVN-V2-SECURE-CHANNEL');

// ====================================================================
// RATE LIMITING & ANTI-REPLAY CACHE
// ====================================================================

define('NONCE_CACHE_FILE', DATA_DIR . '/api_nonces.json');

function checkAndRecordNonce(string $nonceHex): bool {
    $now = time();
    $nonces = readJsonFile(NONCE_CACHE_FILE, []);

    // Clean old nonces older than 10 minutes
    $filtered = [];
    foreach ($nonces as $n => $ts) {
        if ($now - $ts < 600) {
            $filtered[$n] = $ts;
        }
    }

    if (isset($filtered[$nonceHex])) {
        // Replay detected!
        return false;
    }

    $filtered[$nonceHex] = $now;
    writeJsonFile(NONCE_CACHE_FILE, $filtered);
    return true;
}

// ====================================================================
// MAIN REQUEST HANDLER
// ====================================================================

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    echo json_encode(['error' => 'Method not allowed']);
    exit;
}

$rawInput = file_get_contents('php://input');
if (!$rawInput) {
    http_response_code(400);
    echo json_encode(['error' => 'Empty request body']);
    exit;
}

$requestJson = json_decode($rawInput, true);
if (!isset($requestJson['ephemeral_pub'], $requestJson['nonce'], $requestJson['ciphertext'])) {
    http_response_code(400);
    echo json_encode(['error' => 'Invalid packet structure']);
    exit;
}

$clientEphemeralPubHex = $requestJson['ephemeral_pub'];
$nonceHex = $requestJson['nonce'];
$ciphertextHex = $requestJson['ciphertext'];

// 1. Anti-Replay check on Nonce
if (!checkAndRecordNonce($nonceHex)) {
    http_response_code(403);
    echo json_encode(['error' => 'Replay attack rejected']);
    exit;
}

// 2. Derive Shared Secret via ECDH (X25519)
$clientEphemeralPub = @hex2bin($clientEphemeralPubHex);
$nonce = @hex2bin($nonceHex);
$ciphertext = @hex2bin($ciphertextHex);
$serverX25519Priv = @hex2bin(SERVER_X25519_PRIV_HEX);

if (!$clientEphemeralPub || !$nonce || !$ciphertext || !$serverX25519Priv) {
    http_response_code(400);
    echo json_encode(['error' => 'Invalid hex decoding']);
    exit;
}

try {
    // ECDH Scalarmult: client_pub * server_priv
    $sharedSecret = sodium_crypto_scalarmult($serverX25519Priv, $clientEphemeralPub);

    // HKDF-SHA256 Derivation
    $sessionKey = hash_hkdf('sha256', $sharedSecret, 32, PROTOCOL_INFO, PRE_SHARED_PEPPER);

    // 3. Decrypt Client Payload using XChaCha20-Poly1305
    $decryptedJson = sodium_crypto_aead_xchacha20poly1305_ietf_decrypt(
        $ciphertext,
        '',
        $nonce,
        $sessionKey
    );

    if ($decryptedJson === false) {
        throw new Exception('AEAD decryption failed');
    }

    $payload = json_decode($decryptedJson, true);
    if (!isset($payload['license_key'], $payload['device_fp'], $payload['client_ts'], $payload['challenge'])) {
        throw new Exception('Incomplete decrypted payload');
    }

    // 4. Validate Timestamps (Max 60 seconds clock drift allowed)
    $serverTime = time();
    if (abs($serverTime - (int)$payload['client_ts']) > 60) {
        throw new Exception('Clock drift exceeded 60s');
    }

    $licenseKey = trim((string)$payload['license_key']);
    $deviceFp = trim((string)$payload['device_fp']);
    $challenge = (string)$payload['challenge'];

    // 5. Query & Validate License in keys.json
    $keys = readJsonFile(KEYS_FILE, []);
    $foundKey = null;
    $foundIndex = null;

    foreach ($keys as $idx => $k) {
        if (strcasecmp($k['key'], $licenseKey) === 0) {
            $foundKey = $k;
            $foundIndex = $idx;
            break;
        }
    }

    if (!$foundKey) {
        $responsePayload = [
            'status' => 'not_found',
            'exp_ts' => 0,
            'server_ts' => $serverTime,
            'echo_challenge' => $challenge,
            'device_fp' => $deviceFp,
            'session_payload' => '',
        ];
    } elseif (!empty($foundKey['is_banned'])) {
        $responsePayload = [
            'status' => 'banned',
            'exp_ts' => 0,
            'server_ts' => $serverTime,
            'echo_challenge' => $challenge,
            'device_fp' => $deviceFp,
            'session_payload' => '',
        ];
    } else {
        // Check Expiration
        $expTs = 0;
        if (!empty($foundKey['expires_at'])) {
            $expTs = is_numeric($foundKey['expires_at']) ? (int)$foundKey['expires_at'] : strtotime($foundKey['expires_at']);
            if ($expTs > 0 && $expTs < $serverTime) {
                $responsePayload = [
                    'status' => 'expired',
                    'exp_ts' => $expTs,
                    'server_ts' => $serverTime,
                    'echo_challenge' => $challenge,
                    'device_fp' => $deviceFp,
                    'session_payload' => '',
                ];
                goto respond;
            }
        }

        // Check Multi-Device Binding
        $maxDevices = isset($foundKey['max_devices']) ? max(1, (int)$foundKey['max_devices']) : 1;
        $devices = isset($foundKey['devices']) && is_array($foundKey['devices']) ? $foundKey['devices'] : [];

        // Check if device already registered
        $deviceMatched = false;
        foreach ($devices as $dev) {
            if (isset($dev['hwid']) && $dev['hwid'] === $deviceFp) {
                $deviceMatched = true;
                break;
            }
        }

        if (!$deviceMatched) {
            if (count($devices) >= $maxDevices) {
                $responsePayload = [
                    'status' => 'device_limit_reached',
                    'exp_ts' => $expTs,
                    'server_ts' => $serverTime,
                    'echo_challenge' => $challenge,
                    'device_fp' => $deviceFp,
                    'session_payload' => '',
                ];
                goto respond;
            }

            // Register new device
            $devices[] = [
                'hwid' => $deviceFp,
                'first_seen' => date('Y-m-d H:i:s'),
                'last_seen' => date('Y-m-d H:i:s'),
                'ip' => $_SERVER['REMOTE_ADDR'] ?? '',
            ];
            $keys[$foundIndex]['devices'] = $devices;
            writeJsonFile(KEYS_FILE, $keys);
        } else {
            // Update last_seen
            foreach ($devices as &$dev) {
                if ($dev['hwid'] === $deviceFp) {
                    $dev['last_seen'] = date('Y-m-d H:i:s');
                    $dev['ip'] = $_SERVER['REMOTE_ADDR'] ?? '';
                }
            }
            $keys[$foundIndex]['devices'] = $devices;
            writeJsonFile(KEYS_FILE, $keys);
        }

        // Active success payload: Contains encrypted session token/offsets
        $sessionToken = bin2hex(random_bytes(32));
        $responsePayload = [
            'status' => 'active',
            'exp_ts' => $expTs,
            'server_ts' => $serverTime,
            'echo_challenge' => $challenge,
            'device_fp' => $deviceFp,
            'session_payload' => $sessionToken,
        ];
    }

    respond:

    // 6. Ed25519 Detached Signature
    $serverEd25519Priv = @hex2bin(SERVER_ED25519_PRIV_HEX);
    $responseJsonBytes = json_encode($responsePayload, JSON_UNESCAPED_SLASHES);
    $signature = sodium_crypto_sign_detached($responseJsonBytes, $serverEd25519Priv);

    // 7. Encrypt response with Session Key
    $resNonce = random_bytes(24);
    $resCiphertext = sodium_crypto_aead_xchacha20poly1305_ietf_encrypt(
        $responseJsonBytes,
        '',
        $resNonce,
        $sessionKey
    );

    // 8. Output encrypted packet
    echo json_encode([
        'nonce' => bin2hex($resNonce),
        'ciphertext' => bin2hex($resCiphertext),
        'signature' => bin2hex($signature),
    ], JSON_UNESCAPED_SLASHES);

} catch (Exception $e) {
    http_response_code(400);
    echo json_encode(['error' => 'Security check rejected: ' . $e->getMessage()]);
}
